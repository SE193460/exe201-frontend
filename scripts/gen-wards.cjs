/* Generates public/data/vietnam-wards-2025.json — ward/commune names for every
 * province, keyed by the canonical province name used in vietnamProvinces.ts.
 *
 * Usage:
 *   node scripts/gen-wards.cjs <vn-province.cjs> <provinces.geojson> <out.json>
 */
const fs = require("fs");

const [, , srcCjs, geoPath, outPath] = process.argv;
const vn = require(srcCjs);
const geo = JSON.parse(fs.readFileSync(geoPath, "utf8"));

const stripPrefix = (name) => String(name).replace(/^(Thành phố|Tỉnh)\s+/i, "").trim();
const norm = (name) => stripPrefix(name).toLowerCase();

const canonicalByNorm = new Map();
for (const f of geo.features) {
  canonicalByNorm.set(f.properties.name.trim().toLowerCase(), f.properties.name);
}

const result = {};
let matched = 0;
for (const p of vn.provinces) {
  const canonicalName = canonicalByNorm.get(norm(p.name));
  if (!canonicalName) {
    console.warn(`no canonical match for province: ${p.name}`);
    continue;
  }
  matched += 1;
  result[canonicalName] = p.wards.map((w) => w.name).sort((a, b) => a.localeCompare(b, "vi"));
}

const json = JSON.stringify(result);
const header =
  "// AUTO-GENERATED by scripts/gen-wards.cjs — do not edit by hand.\n" +
  "// Ward/commune names for the 34 provincial units (2025 reform, NQ 202/2025/QH15),\n" +
  "// keyed by the province name used in vietnamProvinces.ts.\n\n" +
  "export const VIETNAM_WARDS_2025: Record<string, string[]> = ";
fs.writeFileSync(outPath, header + json + ";\n");
console.log(
  `wrote ${outPath} (${(json.length / 1024).toFixed(0)} KB, ${matched}/${vn.provinces.length} provinces)`,
);
