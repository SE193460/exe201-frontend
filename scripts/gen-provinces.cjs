/* Generates src/data/vietnamProvinces.ts (centres + bounds) from the simplified
 * 34-province GeoJSON. Usage:
 *   node scripts/gen-provinces.cjs public/data/vietnam-provinces-34.geojson src/data/vietnamProvinces.ts */
const fs = require("fs");

const [, , inPath, outPath] = process.argv;
const geo = JSON.parse(fs.readFileSync(inPath, "utf8"));

function ringsOf(geometry) {
  if (geometry.type === "Polygon") return geometry.coordinates;
  if (geometry.type === "MultiPolygon") return geometry.coordinates.flat();
  return [];
}

const rows = geo.features.map((f) => {
  let south = 90;
  let west = 180;
  let north = -90;
  let east = -180;
  let sumLat = 0;
  let sumLng = 0;
  let n = 0;
  for (const ring of ringsOf(f.geometry)) {
    for (const [lng, lat] of ring) {
      if (lat < south) south = lat;
      if (lat > north) north = lat;
      if (lng < west) west = lng;
      if (lng > east) east = lng;
      sumLat += lat;
      sumLng += lng;
      n += 1;
    }
  }
  const center = n ? [Number((sumLat / n).toFixed(5)), Number((sumLng / n).toFixed(5))] : [0, 0];
  const round = (v) => Number(v.toFixed(5));
  return {
    code: String(f.properties.code || ""),
    name: f.properties.name,
    nameEn: f.properties.name_en || f.properties.name,
    fullName: f.properties.full_name || f.properties.name,
    center,
    bounds: [
      [round(south), round(west)],
      [round(north), round(east)],
    ],
  };
});

rows.sort((a, b) => a.name.localeCompare(b.name, "vi"));

const header = `// AUTO-GENERATED by scripts/gen-provinces.cjs — do not edit by hand.
// 34 provincial units per the 2025 administrative reform (NQ 202/2025/QH15).
// \`center\` / \`bounds\` are [lat, lng] pairs derived from the province polygons.

export type VietnamProvince = {
  code: string;
  name: string;
  nameEn: string;
  fullName: string;
  /** Approximate centroid as [lat, lng]. */
  center: [number, number];
  /** Bounding box as [[south, west], [north, east]]. */
  bounds: [[number, number], [number, number]];
};

export const VIETNAM_PROVINCES: VietnamProvince[] = `;

fs.writeFileSync(outPath, header + JSON.stringify(rows, null, 2) + ";\n");
console.log(`wrote ${outPath} (${rows.length} provinces)`);
